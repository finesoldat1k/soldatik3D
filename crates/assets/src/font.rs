//! Built-in 128x128 RGBA bitmap font atlas used by the immediate-mode UI.
//! Glyphs live in 8x8 cells; characters 32..126 are packed in a 16x8 grid.

pub const FONT_ATLAS_SIZE: u32 = 128;

/// Size of one atlas cell in texels. Glyphs occupy the top-left 5x7 texels.
pub const FONT_CELL_SIZE: u32 = 8;

/// Width of a glyph bitmap inside its cell.
pub const FONT_GLYPH_WIDTH: u32 = 5;

/// Height of a glyph bitmap inside its cell.
pub const FONT_GLYPH_HEIGHT: u32 = 7;

/// Number of glyph cells per atlas row.
pub const FONT_GLYPH_COLUMNS: u32 = 16;

const GLYPH_COLUMNS: u32 = FONT_GLYPH_COLUMNS;

/// 128x128 RGBA font atlas. Glyphs live in 8x8 cells, characters 32..126 are
/// packed in a 16x8 grid. The glyph itself is a 5x7 bitmap.
pub fn font_atlas_rgba8() -> Vec<u8> {
    let mut pixels = vec![0u8; (FONT_ATLAS_SIZE * FONT_ATLAS_SIZE * 4) as usize];
    let size = FONT_ATLAS_SIZE;

    for code in 32u32..127 {
        let glyph = glyph_rows(code as u8 as char);
        let cell_x = (code % GLYPH_COLUMNS) * FONT_CELL_SIZE;
        let cell_y = (code / GLYPH_COLUMNS) * FONT_CELL_SIZE;

        for row in 0..7u32 {
            for col in 0..5u32 {
                if (glyph[row as usize] & (1 << (4 - col))) != 0 {
                    let px = cell_x + col;
                    let py = cell_y + row;
                    let idx = ((py * size + px) * 4) as usize;
                    pixels[idx..idx + 4].copy_from_slice(&[255, 255, 255, 255]);
                }
            }
        }
    }

    pixels
}

