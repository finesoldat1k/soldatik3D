// Framebuffer для offscreen render pass (один attachment)
pub fn create_offscreen_framebuffer(
    device: &Device, render_pass: vk::RenderPass, view: vk::ImageView, extent: vk::Extent2D,
) -> Result<vk::Framebuffer> {
    let attachments = [view];
    let info = vk::FramebufferCreateInfo::default()
        .render_pass(render_pass).attachments(&attachments)
        .width(extent.width).height(extent.height).layers(1);
    Ok(unsafe { device.create_framebuffer(&info, None)? })
}

